#include<iostream>
using namespace std;
int main(){
    int a=10;
    a+=5;
    cout<<"a="<<a<<"\n";             //Addition operator



    int b;
    b=20;
    cout<<"b="<<b<<"\n";            //Subtraction operator



    int c;
    c=30;
    c*=2;
    cout<<"c="<<c<<"\n";             //Multiplication operator



    int d;
    d=55;
    d/=5;
    cout<<"d="<<d<<"\n";             //Division operator


    return 0;
}


